#!/usr/bin/env python3
"""Generate unity/Assets/Scripts/Core/RosterHitfit.cs from src/core/roster_hitfit.inc (the C++ hit-fit table)."""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src/core/roster_hitfit.inc"
DST = ROOT / "unity/Assets/Scripts/Core/RosterHitfit.cs"
ENTRY = re.compile(r"^\s*\{(.*)\},\s*(//.*)?$")
DECIMAL = re.compile(r"^-?\d+\.\d*$")
IDENT = re.compile(r"^[A-Za-z_]\w*$")


def token(t, first):
    t = t.strip()
    if first:
        return t  # the quoted fighter id
    if DECIMAL.match(t):
        return t + "f"
    if IDENT.match(t):
        return "MoveId." + t
    return t


def main():
    rows = []
    for n, line in enumerate(SRC.read_text(encoding="utf-8").splitlines(), 1):
        s = line.strip()
        if not s or s.startswith("//"):
            continue
        m = ENTRY.match(line)
        if not m:
            sys.exit(f"{SRC}:{n}: not an entry: {line!r}")
        toks = m.group(1).split(",")
        if len(toks) != 11:
            sys.exit(f"{SRC}:{n}: {len(toks)} fields, expected 11")
        args = ", ".join(token(t, i == 0) for i, t in enumerate(toks))
        rows.append(f"            new HitFit({args}),{'  ' + m.group(2) if m.group(2) else ''}")
    out = [
        "// Generated by scripts/gen_hitfit_cs.py from src/core/roster_hitfit.inc: do not edit by hand.",
        "namespace ClashHorizon.Core",
        "{",
        "    internal readonly struct HitFit",
        "    {",
        "        public readonly string fighter;",
        "        public readonly int slot, move, index;",
        "        public readonly float was, x, y, r, a0, a1, reach1;",
        "",
        "        public HitFit(string fighter, int slot, int move, int index, float was, float x, float y, float r, float a0, float a1,",
        "                      float reach1)",
        "        {",
        "            this.fighter = fighter; this.slot = slot; this.move = move; this.index = index; this.was = was;",
        "            this.x = x; this.y = y; this.r = r; this.a0 = a0; this.a1 = a1; this.reach1 = reach1;",
        "        }",
        "    }",
        "",
        "    internal static class RosterHitfit",
        "    {",
        "        internal static readonly HitFit[] entries =",
        "        {",
        *rows,
        "        };",
        "    }",
        "}",
        "",
    ]
    DST.write_text("\n".join(out), encoding="utf-8")
    print(f"{DST.relative_to(ROOT)}: {len(rows)} entries")


if __name__ == "__main__":
    main()
